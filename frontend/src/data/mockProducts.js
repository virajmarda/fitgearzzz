// Build size/weight variants from a list of option values.
const buildVariants = (handle, optionName, values, basePrice, compareAt) =>
  values.map((v, i) => ({
    id: `${handle}-v${i + 1}`,
    title: typeof v === 'string' ? v : v.title,
    available: typeof v === 'object' ? v.available !== false : true,
    price: typeof v === 'object' && v.price != null ? v.price : basePrice,
    compareAtPrice:
      typeof v === 'object' && v.compareAtPrice != null
        ? v.compareAtPrice
        : compareAt ?? null,
    options: { [optionName]: typeof v === 'string' ? v : v.title },
  }));

